/**
 * 调试模式（仅测试环境）。
 *
 * ## 目的
 *
 * 让测试人员能**直接点任意一关**进入，不用从第 1 关一路打上去。
 * 1000 关手动打过来不现实；想复现某个具体关卡的 bug 也几乎不可能。
 *
 * ## 为什么用构建期常量而不是 `import.meta.env`
 *
 * 微信小游戏走的是另一条构建链（`mode === 'wx'`），
 * `import.meta.env` 在那里不一定有定义 —— 用它会导致微信端构建直接报错。
 *
 * 所以统一用 Vite `define` 注入的编译期常量：
 * - `__DEBUG__` = `'true'` / `'false'`
 * - 死代码消除：生产构建（`mode === 'production'`）产出 `'false'`，
 *   整块调试分支被 tree-shake 掉，调试入口在正式包��**不存在**
 *
 * ## 安全性：客户端和服务器各判各的
 *
 * 客户端的开关只管**界面**（要不要显示「调试模式」标记、要不要允许点锁着的关）。
 *
 * 服务端有**独立**的配置项 `debug: true`（见 `server/internal/core/config.go`），
 * 管的是「要不要真的执行跳关」。客户端绕过不算数 ——
 * 服务端必须自己判断这个请求合不合法。
 */
declare const __DEBUG__: string;

/** 是否处于调试模式（测试环境）。 */
export const DEBUG_ENABLED: boolean = __DEBUG__ === 'true';
